def process_data(data_dict):
    processed_data = []
    for g_protein, treatments in data_dict.items():
        for treatment, values in treatments.items():
            for val in values:
                # Invert sign as per chart logic (negative values in data -> positive bars)
                processed_data.append({
                    'G_Protein': g_protein,
                    'Treatment': treatment,
                    'Value': -1 * val
                })
    return pd.DataFrame(processed_data)

def calculate_tukey(data_dict):
    order = ['Gq', 'G11', 'G15', 'Gi1', 'Gi2', 'Gi3', 'GoA', 'GoB', 'Gz', 'Gg', 'GsS', 'GsL', 'G12', 'G13']
    df = process_data(data_dict)
    
    tukey_results = {}
    for protein in order:
        protein_data = df[df['G_Protein'] == protein]
        if len(protein_data) > 0:
            try:
                tukey = pairwise_tukeyhsd(endog=protein_data['Value'], groups=protein_data['Treatment'], alpha=0.05)
                # Convert results to a dictionary
                p_values = {}
                # tukey.summary().data is list of lists.
                # row 0 is header.
                header = tukey.summary().data[0]
                # find indices
                try:
                    g1_idx = header.index('group1')
                    g2_idx = header.index('group2')
                    p_idx = header.index('p-adj')
                except ValueError:
                    # Fallback for old statsmodels versions?
                    continue
                
                for row in tukey.summary().data[1:]:
                    g1, g2, p = str(row[g1_idx]), str(row[g2_idx]), float(row[p_idx])
                    p_values[f"{g1}-{g2}"] = p
                    p_values[f"{g2}-{g1}"] = p
                tukey_results[protein] = p_values
            except Exception as e:
                # print(f"Error in tukey for {protein}: {e}")
                tukey_results[protein] = {}
    return tukey_results


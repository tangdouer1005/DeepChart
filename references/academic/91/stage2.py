# ---------------------------------------------------------------------
# Read and prepare data
# ---------------------------------------------------------------------
df = pd.read_csv(io.StringIO(csv_data))

parental = df["Parental"].astype(float)
ln = df["LN"].astype(float)

parental = parental[~parental.isna()]
ln = ln[~ln.isna()]

# ---------------------------------------------------------------------
# Determine output path
# ---------------------------------------------------------------------
outname = "output.png"
if len(sys.argv) > 1:
    outname = sys.argv[1]

# ---------------------------------------------------------------------
# Plot
# ---------------------------------------------------------------------
plt.rcParams.update({
    "font.family": "Arial",
    "axes.linewidth": 1.5,
})

fig, ax = plt.subplots(figsize=(3.2, 5), dpi=300)

x_positions = [0, 1]

bar_colors = ["#c0c0c0", "#98d68c"]
scatter_colors = ["#000000", "#1f7a1f"]

means = [parental.mean(), ln.mean()]
stds = [parental.std(ddof=1), ln.std(ddof=1)]

bar_width = 0.6
ax.bar(
    x_positions,
    means,
    width=bar_width,
    color=bar_colors,
    edgecolor="black",
    linewidth=1.5,
    zorder=1,
)

ax.errorbar(
    x_positions,
    means,
    yerr=stds,
    fmt="none",
    ecolor="black",
    elinewidth=1.5,
    capsize=6,
    capthick=1.5,
    zorder=3,
)

rng = np.random.default_rng(0)
jitter_scale = 0.08

for i, data in enumerate([parental, ln]):
    x_jitter = rng.normal(loc=x_positions[i], scale=jitter_scale, size=len(data))
    ax.scatter(
        x_jitter,
        data,
        s=14,
        color=scatter_colors[i],
        edgecolors="none",
        zorder=4,
        alpha=0.9,
    )

ax.set_xlim(-0.5, 1.5)
ax.set_ylim(0, 6.0)

ax.set_ylabel("Relative FSP1 levels", fontsize=10)
ax.set_xticks(x_positions)
ax.set_xticklabels(["Parental", "LN"], fontsize=9, rotation=45, ha="right")

ax.tick_params(axis="y", labelsize=9, width=1.5, length=4)
ax.tick_params(axis="x", width=1.5, length=0)

ax.yaxis.grid(True, linestyle="-", linewidth=0.5, color="#d0d0d0", zorder=0)
ax.set_axisbelow(True)

for spine in ["top", "right"]:
    ax.spines[spine].set_visible(False)

ax.text(-0.45, 6.2, "h", fontsize=18, fontweight="bold", ha="left", va="top")

ax.text(
    0.5,
    5.8,
    r"$P < 1 \times 10^{-15}$",
    ha="center",
    va="center",
    fontsize=10,
)

plt.tight_layout()
fig.savefig(outname, bbox_inches="tight")
plt.close(fig)
    data=df_300,
    x="Model",
    y="AUROC",
    order=order,
    width=0.15,
    showcaps=True,
    boxprops={"facecolor": "white", "edgecolor": "black", "linewidth": 1},
    whiskerprops={"color": "black", "linewidth": 1},
